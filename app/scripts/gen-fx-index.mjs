// Writes src/fx/effects/index.generated.ts, which imports every effect's
// definition.ts and pass.ts so the registries in fx-registry.ts and
// fx-shaders/registry.ts pick up a new effect folder without edits, and
// src/fx/effects/processors.generated.ts, which imports every audio effect's
// processor.ts for the audio chain (see audio-mix/chain.ts). The processors
// get their own index so the chain worklet bundles them without the
// definitions and shader passes. It also writes the generated index of each
// per-type registry in TYPE_REGISTRIES, so a new type adds its file and edits
// nothing else. Runs before dev, build, lint and the unit
// tests; the output is committed so a fresh checkout type-checks, and CI runs
// it with `--check` to fail when a committed copy is stale.
//
//   node scripts/gen-fx-index.mjs          regenerate the indexes
//   node scripts/gen-fx-index.mjs --check  exit 1 if an index is stale

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const APP_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const EFFECTS_DIR = join(APP_DIR, "src", "fx", "effects");
const INDEX_PATH = join(EFFECTS_DIR, "index.generated.ts");
const PROCESSORS_PATH = join(EFFECTS_DIR, "processors.generated.ts");

// Effects whose types are one file each in a folder: every `*.ts` file in
// `dir` but tests and generated files exports `exportName`, and the index
// lists them all as `listName`.
const TYPE_REGISTRIES = [
  {
    dir: join(EFFECTS_DIR, "transition", "types"),
    exportName: "transitionType",
    typeName: "TransitionTypeDefinition",
    typeModule: "../type.ts",
    listName: "TRANSITION_TYPE_MODULES",
  },
];

// "negative-split" -> "negativeSplit".
function identifierFor(folder) {
  return folder.replace(/-([a-z0-9])/g, (_, letter) => letter.toUpperCase());
}

function effectFolders() {
  return readdirSync(EFFECTS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((folder) => existsSync(join(EFFECTS_DIR, folder, "definition.ts")))
    .sort();
}

function arrayLines(names) {
  return names.map((name) => `  ${name},`).join("\n");
}

function renderIndex(folders) {
  const imports = [
    'import type { EffectPass } from "../../fx-shaders/types.ts";',
    'import type { FxEffectDefinitionModule } from "../types.ts";',
  ];
  const definitions = [];
  const passes = [];
  for (const folder of folders) {
    const name = identifierFor(folder);
    imports.push(`import * as ${name} from "./${folder}/definition.ts";`);
    definitions.push(name);
    if (existsSync(join(EFFECTS_DIR, folder, "pass.ts"))) {
      imports.push(
        `import { pass as ${name}Pass } from "./${folder}/pass.ts";`,
      );
      passes.push(`${name}Pass`);
    }
  }

  return `// Generated by scripts/gen-fx-index.mjs from the effect folders. Do not
// edit; run \`pnpm --dir app run gen:fx-index\` after adding an effect.

${imports.join("\n")}

// Every effect folder's definition.ts, in folder order.
export const EFFECT_DEFINITION_MODULES: readonly FxEffectDefinitionModule[] = [
${arrayLines(definitions)}
];

// Every effect folder's pass.ts, in folder order.
export const EFFECT_PASSES: readonly EffectPass[] = [
${arrayLines(passes)}
];
`;
}

function renderProcessors(folders) {
  const imports = [
    'import type { AudioEffectDsp } from "../../audio-mix/processor.ts";',
  ];
  const processors = [];
  for (const folder of folders) {
    if (existsSync(join(EFFECTS_DIR, folder, "processor.ts"))) {
      const name = `${identifierFor(folder)}Processor`;
      imports.push(
        `import { processor as ${name} } from "./${folder}/processor.ts";`,
      );
      processors.push(name);
    }
  }

  return `// Generated by scripts/gen-fx-index.mjs from the effect folders. Do not
// edit; run \`pnpm --dir app run gen:fx-index\` after adding an effect.

${imports.join("\n")}

// Every audio effect folder's processor.ts, in folder order.
export const EFFECT_AUDIO_PROCESSORS: readonly AudioEffectDsp[] = [
${arrayLines(processors)}
];
`;
}

function typeFiles(dir) {
  return readdirSync(dir)
    .filter(
      (file) =>
        file.endsWith(".ts") &&
        !file.endsWith(".test.ts") &&
        !file.endsWith(".generated.ts"),
    )
    .sort();
}

function renderTypeIndex(registry) {
  const imports = [
    `import type { ${registry.typeName} } from "${registry.typeModule}";`,
  ];
  const names = [];
  for (const file of typeFiles(registry.dir)) {
    const name = identifierFor(file.replace(/\.ts$/, ""));
    imports.push(
      `import { ${registry.exportName} as ${name} } from "./${file}";`,
    );
    names.push(name);
  }

  return `// Generated by scripts/gen-fx-index.mjs from the files in this folder. Do
// not edit; run \`pnpm --dir app run gen:fx-index\` after adding a type.

${imports.join("\n")}

// Every type file in this folder, in file order.
export const ${registry.listName}: readonly ${registry.typeName}[] = [
${arrayLines(names)}
];
`;
}

// Writes `expected` to `file` unless it already holds it; with `check`,
// reports a stale file instead.
function sync(file, expected, check) {
  const actual = existsSync(file)
    ? readFileSync(file, "utf8").replace(/\r\n/g, "\n")
    : undefined;
  const path = relative(process.cwd(), file);
  if (actual === expected) {
    return;
  }

  if (check) {
    console.error(
      `${path} is out of date. Run \`pnpm --dir app run gen:fx-index\` and commit the result.`,
    );
    process.exitCode = 1;
    return;
  }

  writeFileSync(file, expected);
  console.log(`Wrote ${path}`);
}

function main() {
  const check = process.argv.includes("--check");
  const folders = effectFolders();
  sync(INDEX_PATH, renderIndex(folders), check);
  sync(PROCESSORS_PATH, renderProcessors(folders), check);
  for (const registry of TYPE_REGISTRIES) {
    sync(
      join(registry.dir, "index.generated.ts"),
      renderTypeIndex(registry),
      check,
    );
  }
}

main();
